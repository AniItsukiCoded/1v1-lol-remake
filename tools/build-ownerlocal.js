#!/usr/bin/env node
/* Bundles functions/lib/{owner,economy,rankcore}.js + functions/catalog.json into js/ownerlocal.js, so an OWNER's browser can run the very same
   owner commands directly against the Realtime Database when the "owner" Cloud Function is not deployed / not reachable (no Blaze plan yet).
   Authorisation is still the database rules: only ownerUids/<uid> may write the paths these commands touch (see tools/build-rules.js).
   Loaded lazily by js/admin.js, only for owners. Runs automatically before `firebase deploy` and via `npm run ownerlocal`. */
const fs=require('fs'),path=require('path'),R=f=>fs.readFileSync(path.join(__dirname,'..','functions',f),'utf8');
const out=`/* GENERATED by tools/build-ownerlocal.js - do not edit. Owner commands that run in the owner's browser when the Cloud Function is unreachable. */
window.OWNERLOCAL=(()=>{const M={},C={};const req=n=>{n=n.replace(/^.*\\//,'');if(C[n])return C[n].exports;const m=C[n]={exports:{}};M[n](m,m.exports,req);return m.exports};
M['catalog.json']=(module)=>{module.exports=${R('catalog.json')}};
M['rankcore.js']=function(module,exports,require){${R('lib/rankcore.js')}\n};
M['economy.js']=function(module,exports,require){${R('lib/economy.js')}\n};
M['owner.js']=function(module,exports,require){${R('lib/owner.js')}\n};
return{handle:req('owner.js').handle}})();
`;
fs.writeFileSync(path.join(__dirname,'..','js','ownerlocal.js'),out);console.log('js/ownerlocal.js written ('+out.length+' bytes)');
